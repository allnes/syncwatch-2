"""Generate the native helper's policy from the shared startup profile."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2]
PROFILE = ROOT / "tools/python-runtime/profile.json"
GENERATED = ROOT / "packages/python-startup/policy.generated.h"


def render(profile):
    policy = profile["startupPolicy"]
    blocks = []
    for name, key in (("PRECONFIG", "preConfig"), ("CONFIG", "config")):
        values = policy[key]
        if not isinstance(values, dict) or not values or any(
                not isinstance(field, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", field) or type(value) is not int or value not in (0, 1)
                for field, value in values.items()):
            raise ValueError("Expected named boolean integer startup fields")
        blocks.append(macro(name, [f"{field}, {value}" for field, value in sorted(values.items())]))
    fields = policy["explicitPathFields"]
    if not isinstance(fields, list) or not fields or any(
            not isinstance(field, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", field) for field in fields) or len(set(fields)) != len(fields):
        raise ValueError("Expected unique named explicit path fields")
    blocks.append(macro("PATH_FIELDS", fields))
    return ("/* SPDX-License-Identifier: Apache-2.0 */\n"
            "/* Generated by tools/python-runtime/generate_policy.py. */\n"
            "#ifndef SYNCWATCH_PYTHON_POLICY_GENERATED_H\n#define SYNCWATCH_PYTHON_POLICY_GENERATED_H\n\n"
            + "\n\n".join(blocks) + "\n\n#endif\n")


def macro(name, values):
    return f"#define SW_PYTHON_{name}(X) \\\n" + " \\\n".join("    X(" + value + ")" for value in values)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = render(json.loads(PROFILE.read_text(encoding="utf-8")))
    if args.check:
        if GENERATED.read_text(encoding="utf-8") != data:
            raise ValueError("Native startup policy must be regenerated")
    else:
        GENERATED.write_text(data, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
