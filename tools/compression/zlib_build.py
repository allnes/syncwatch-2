"""Build and semantically revalidate the selected source-pinned static zlib."""

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

from toolchain import resolve

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/dependencies"))
from source_files import archive_bytes, digest, encoded, read_snapshot

COMPONENT = "zlib"


def profile_data():
    profile = json.loads((ROOT / "tools/compression/profile.json").read_text())
    component = json.loads((ROOT / "tools/dependencies/components.json").read_text())["components"][COMPONENT]
    source = profile["source"]
    expected = {k: source[k] for k in ("revision", "license", "notices", "exports")}
    expected.update(requires=[], unusedSubmodules={})
    if profile["schemaVersion"] != 1 or profile["sharedLibrary"] is not False:
        raise ValueError("Only the reviewed static zlib profile is supported")
    if component["sources"] != {source["path"]: expected} or component["roots"] != [source["path"]]:
        raise ValueError("Compression source/license profile differs from the registered graph")
    return profile


def validate_sources(files, profile):
    match = re.search(rb'set\(ZLIB_SRCS\s+(.*?)\)', files["CMakeLists.txt"], re.S)
    if not match or match.group(1).decode().split() != profile["compileSources"]:
        raise ValueError("Upstream compiled source set differs from the reviewed profile")
    if b'#define ZLIB_VERSION "' + profile["version"].encode() + b'"' not in files["zlib.h"]:
        raise ValueError("Unexpected upstream header version")
    if digest(archive_bytes(files)) != profile["sourceArchiveSha256"]:
        raise ValueError("Unchanged source archive differs from the reviewed profile")


def execute(command):
    subprocess.run(command, cwd=ROOT, check=True, timeout=180)


def configure(cmake, sdk_args, source, directory, artifact=None, headers=None):
    command = [cmake, "-S", str(ROOT / "tools/compression"), "-B", str(directory), *sdk_args,
               "-DCMAKE_BUILD_TYPE=Release", "-DCMAKE_FIND_USE_PACKAGE_REGISTRY=OFF",
               "-DCMAKE_FIND_USE_SYSTEM_PACKAGE_REGISTRY=OFF", "-DSYNCWATCH_ZLIB_SOURCE=" + str(source)]
    if artifact is not None:
        command += ["-DSYNCWATCH_ZLIB_ARTIFACT=" + str(artifact), "-DSYNCWATCH_ZLIB_HEADERS=" + str(headers)]
    execute(command)


def compile_probe(cmake, directory):
    execute([cmake, "--build", str(directory), "--config", "Release", "--target", "zlib_probe", "--parallel", "2"])
    return Path((directory / "library-Release.txt").read_text()), Path((directory / "probe-Release.txt").read_text())


def validate_probe(report, profile):
    if (set(report) != {"version", "pointerBits", "cases"} or report["version"] != profile["version"]
            or type(report["pointerBits"]) is not int or report["pointerBits"] != 64
            or report["cases"] != profile["probeCases"]):
        raise ValueError("Native compression probe did not satisfy its contract")


def native_probe(executable, directory, profile):
    fixture = directory / "fixture.gz"
    process = subprocess.run([str(executable), profile["version"], str(fixture)], text=True,
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=30)
    if process.returncode:
        raise ValueError("Native compression probe failed:\n" + process.stdout)
    report = json.loads(process.stdout)
    validate_probe(report, profile)
    if fixture.exists():
        raise ValueError("Native compression probe did not remove its owned fixture")
    return report


def expected_payload(files, profile, sdk, library, configured_header, probe):
    validate_probe(probe, profile)
    if not library.startswith(b"!<arch>\n"):
        raise ValueError("Expected a static native archive")
    library_name = "zlibstatic.lib" if sdk["target"] == "windows-x64" else "libzlibstatic.a"
    contents = {"lib/" + library_name: library, "include/zlib.h": files["zlib.h"],
                "include/zconf.h": configured_header, "sources.zip": archive_bytes(files)}
    for name in profile["source"]["notices"]:
        contents["notices/zlib/" + name] = files[name]
    contents["build-report.json"] = encoded({"schemaVersion": 1, "version": profile["version"],
                                             "source": profile["source"], "sdk": sdk, "profile": "static-native-v1",
                                             "sourceFilesUnchanged": True, "sharedLibrary": False,
                                             "configuredHeader": "Generated by upstream CMake; SyncWatch adds a configuration notice",
                                             "syncplayRuntimeReady": False, "probe": probe,
                                             "files": {n: digest(d) for n, d in contents.items()}})
    return contents


def verify_files(payload, expected):
    found = set()
    for entry in payload.rglob("*"):
        if entry.is_symlink():
            raise ValueError("Compression payload contains a symbolic link")
        if entry.is_file():
            name = entry.relative_to(payload).as_posix()
            found.add(name)
            if name not in expected or entry.read_bytes() != expected[name]:
                raise ValueError("Compression payload/source/notice differs: " + name)
    if found != set(expected):
        raise ValueError("Compression payload has missing or unexpected files")


def materialize(directory, files):
    directory.mkdir()
    for name, data in files.items():
        path = directory / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def configuration_header(path):
    return (b"/* Configured by upstream CMake for SyncWatch static-native-v1. Platform configuration differs from original zconf.h. */\n"
            + path.read_bytes())


def require_identical_library(original, repeated):
    if repeated != original:
        offset = next((n for n, (a, b) in enumerate(zip(original, repeated)) if a != b), min(len(original), len(repeated)))
        start, end = max(0, offset - 32), offset + 96
        raise ValueError("Repeated native static build changed its binary bytes: " + json.dumps({
            "sizes": [len(original), len(repeated)], "sha256": [digest(original), digest(repeated)],
            "firstDifference": offset, "contextOffset": start,
            "originalContext": repr(original[start:end]), "repeatedContext": repr(repeated[start:end])}))


def build_or_verify(operation, payload, files, profile, cmake, sdk_args, sdk):
    validate_sources(files, profile)
    # Work stays outside the source snapshot and payload. No build SDK/runtime
    # executable or native test process is distributed in the component.
    with tempfile.TemporaryDirectory(prefix="syncwatch-zlib-") as temporary:
        directory = Path(temporary)
        source = directory / "source"
        materialize(source, files)
        if operation == "build":
            configure(cmake, sdk_args, source, directory / "cold")
            library_path, probe_path = compile_probe(cmake, directory / "cold")
            library = library_path.read_bytes()
            probe = native_probe(probe_path, directory, profile)
            configured_header = configuration_header(directory / "cold/upstream/zconf.h")
            configure(cmake, sdk_args, source, directory / "repeat")
            repeated, repeated_probe = compile_probe(cmake, directory / "repeat")
            require_identical_library(library, repeated.read_bytes())
            if native_probe(repeated_probe, directory, profile) != probe:
                raise ValueError("Repeated native build changed its probe result")
            expected = expected_payload(files, profile, sdk, library, configured_header, probe)
            for name, data in expected.items():
                destination = payload / name
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(data)
        else:
            library_path = payload / "lib" / ("zlibstatic.lib" if sdk["target"] == "windows-x64" else "libzlibstatic.a")
            if not library_path.is_file() or library_path.is_symlink():
                raise ValueError("Missing regular static library")
            configure(cmake, sdk_args, source, directory / "verified", library_path, payload / "include")
            configured_header = configuration_header(directory / "verified/upstream/zconf.h")
            retained = json.loads((payload / "build-report.json").read_text())
            expected = expected_payload(files, profile, sdk, library_path.read_bytes(), configured_header, retained["probe"])
            verify_files(payload, expected)
            _unused, probe_path = compile_probe(cmake, directory / "verified")
            probe = native_probe(probe_path, directory, profile)
            expected = expected_payload(files, profile, sdk, library_path.read_bytes(), configured_header, probe)
        verify_files(payload, expected)
        return {"component": COMPONENT, "target": sdk["target"], "version": profile["version"],
                "sourceFiles": len(files), "sourceArchiveSha256": profile["sourceArchiveSha256"],
                "probe": probe, "syncplayRuntimeReady": False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=("build", "verify"))
    parser.add_argument("--platform", choices=("macos-arm64", "windows-x64", "linux-x64"))
    args = parser.parse_args()
    profile = profile_data()
    cmake, sdk_args, sdk = resolve()
    if args.platform and args.platform != sdk["target"]:
        raise ValueError("Compression artifact must be validated on its native host")
    if args.operation == "build":
        if json.loads(os.environ["SYNCWATCH_DEPENDENCY_FLAGS"]) != {"profile": "static-native-v1", "version": profile["version"]}:
            raise ValueError("Unknown compression build profile")
        snapshot = Path(os.environ["SYNCWATCH_DEPENDENCY_SOURCES"]) / profile["source"]["path"]
        payload = Path(os.environ["SYNCWATCH_DEPENDENCY_OUTPUT"])
    else:
        workspace = ROOT / "artifacts/dependencies/zlib" / sdk["target"]
        snapshot, payload = workspace / "zlib.tar", workspace / "payload"
    files = read_snapshot(snapshot, profile["source"])
    print(json.dumps(build_or_verify(args.operation, payload, files, profile, cmake, sdk_args, sdk), sort_keys=True))


if __name__ == "__main__":
    main()
