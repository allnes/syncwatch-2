// Native SyncWatch resource formats. Inputs are validated before Style Dictionary resolves aliases.
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0;
export const identifier = id => id.split('.').map(part => part[0].toUpperCase() + part.slice(1)).join('');
const swiftName = id => { const name = identifier(id); return name[0].toLowerCase() + name.slice(1); };
export const number = value => String(Math.round(value * 1e6) / 1e6);
export const color = value => {
    if (typeof value !== 'string' || !/^#[\da-f]{6}([\da-f]{2})?$/i.test(value)) throw Error('Expected sRGB #RRGGBB or #RRGGBBAA');
    return value.toUpperCase() + (value.length === 7 ? 'FF' : '');
};
const bytes = value => value.slice(1).match(/../g).map(byte => parseInt(byte, 16));
const csharpColor = value => { const [r, g, b, a] = bytes(value); return `Color.FromArgb(${a}, ${r}, ${g}, ${b})`; };
const swiftColor = value => { const [r, g, b, a] = bytes(value); return `Color(\n        .sRGB, red: ${r}.0 / 255, green: ${g}.0 / 255, blue: ${b}.0 / 255, opacity: ${a}.0 / 255)`; };
const wpfColor = value => '#' + value.slice(7) + value.slice(1, 7);
const header = '// Generated by tools/design/generate.mjs. Do not edit.\n// SPDX-License-Identifier: Apache-2.0\n';

export function validateTokens(tokens) {
    const ids = new Map();
    const names = new Set(['colors', 'dimensions', 'class', 'struct', 'enum', 'protocol', 'extension', 'func', 'import', 'let', 'var', 'static', 'public', 'private', 'internal', 'return', 'switch', 'case', 'default', 'self', 'super', 'typealias', 'associatedtype', 'deinit', 'init', 'subscript', 'where', 'inout', 'operator', 'precedencegroup', 'throw', 'throws', 'rethrows', 'try', 'catch', 'do', 'defer', 'if', 'else', 'for', 'while', 'repeat', 'break', 'continue', 'fallthrough', 'as', 'is', 'nil', 'true', 'false', 'any', 'some', 'await', 'async', 'when', 'val', 'fun', 'object', 'package', 'typeof', 'this', 'null']);
    function walk(group, path = []) {
        if (!group || typeof group !== 'object' || Array.isArray(group)) throw Error('Invalid token group: ' + path.join('.'));
        if (Object.hasOwn(group, 'value')) {
            const id = path.join('.');
            if (!path.length || Object.keys(group).some(key => !['value', 'type'].includes(key))) throw Error('Unsupported token fields: ' + id);
            if (!['color', 'number'].includes(group.type)) throw Error('Unknown token type: ' + id);
            const name = identifier(id).toLowerCase();
            if (names.has(name)) throw Error('Native identifier collision: ' + id);
            names.add(name); ids.set(id, group);
        } else for (const [key, child] of Object.entries(group)) {
            if (!/^[a-z][a-zA-Z0-9]*$/.test(key)) throw Error('Invalid token identifier: ' + key);
            walk(child, [...path, key]);
        }
    }
    walk(tokens);
    if (!ids.size) throw Error('Empty token source');
    for (const [id, token] of ids) {
        if (typeof token.value === 'string' && /^\{[a-zA-Z0-9.]+\}$/.test(token.value)) {
            const target = ids.get(token.value.slice(1, -1));
            if (!target || target.type !== token.type) throw Error('Missing or differently typed reference: ' + id);
        } else validateValue(id, token.type, token.value);
    }
    return ids;
}
function validateValue(id, type, value) {
    if (type === 'color') color(value);
    else if (type !== 'number' || typeof value !== 'number' || !Number.isFinite(value) || value < 0 || value > 1e6) {
        throw Error('Expected a finite logical dimension in [0, 1000000]: ' + id);
    }
}
export function validateThemes(spec, ids) {
    if (spec.schemaVersion !== 1 || spec.units !== 'logical' || !spec.themes ||
        Object.keys(spec.themes).sort().join(',') !== 'dark,light') throw Error('Unsupported native theme contract');
    const roles = Object.keys(spec.themes.dark).sort(compare);
    if (!roles.length || roles.join(',') !== Object.keys(spec.themes.light).sort(compare).join(',')) throw Error('Theme roles must match');
    for (const theme of Object.values(spec.themes)) for (const [role, id] of Object.entries(theme)) {
        if (!/^[a-z][a-zA-Z0-9]*$/.test(role) || ids.get(id)?.type !== 'color') throw Error('Invalid theme role: ' + role);
    }
}
export function normalized(dictionary) {
    return dictionary.allTokens.map(token => {
        const id = token.path.join('.');
        validateValue(id, token.type, token.value);
        return {id, type: token.type, value: token.type === 'color' ? color(token.value) : Number(number(token.value))};
    }).sort((a, b) => compare(a.id, b.id));
}
export function swift(tokens, spec) {
    const roles = Object.keys(spec.themes.dark).sort(compare);
    return header + 'import SwiftUI\n\npublic enum SyncWatchTokens {\n' + tokens.map(t =>
        `    public static let ${swiftName(t.id)}${t.type === 'number' ? ': CGFloat' : ''} = ${t.type === 'color' ? swiftColor(t.value) : number(t.value)}\n`
    ).join('') + '\n    public static let colors: [String: Color] = [\n' + tokens.filter(t => t.type === 'color').map(t => `        "${t.id}": ${swiftName(t.id)},\n`).join('') + '    ]\n\n    public static let dimensions: [String: CGFloat] = [\n' + tokens.filter(t => t.type === 'number').map(t => `        "${t.id}": ${swiftName(t.id)},\n`).join('') + '    ]\n}\n\npublic struct SyncWatchTheme: Sendable {\n' + roles.map(role => `    public let ${role}: Color\n`).join('') +
        '\n' + Object.entries(spec.themes).sort(([a], [b]) => compare(a, b)).map(([theme, values]) =>
            `    public static let ${theme} = SyncWatchTheme(\n` + roles.map((role, i) => `        ${role}: SyncWatchTokens.${swiftName(values[role])}${i < roles.length - 1 ? ',' : ''}\n`).join('') + '    )\n'
        ).join('\n') + '\n    public static func resolve(_ colorScheme: ColorScheme) -> SyncWatchTheme {\n        colorScheme == .dark ? .dark : .light\n    }\n}\n';
}
export function csharp(tokens) {
    return header + '#nullable enable\nusing System.Windows;\nusing System.Windows.Media;\n\nnamespace SyncWatch.Design;\n\npublic static class SyncWatchTokens\n{\n' + tokens.map(t =>
        t.type === 'color' ? `    public static Color ${identifier(t.id)} => ${csharpColor(t.value)};\n` :
            `    public const double ${identifier(t.id)} = ${number(t.value)};\n    public static Thickness ${identifier(t.id)}Thickness => new(${identifier(t.id)});\n    public static CornerRadius ${identifier(t.id)}CornerRadius => new(${identifier(t.id)});\n`
    ).join('') + '}\n';
}
export function xaml(tokens, spec) {
    return '<!-- Generated by tools/design/generate.mjs. Do not edit. SPDX-License-Identifier: Apache-2.0 -->\n' +
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\n' +
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"\n' +
        '                    xmlns:sys="clr-namespace:System;assembly=System.Runtime">\n' + tokens.map(t => t.type === 'color' ?
            `    <Color x:Key="${t.id}">${wpfColor(t.value)}</Color>\n    <SolidColorBrush x:Key="${t.id}.brush" Color="{StaticResource ${t.id}}" />\n` :
            `    <sys:Double x:Key="${t.id}">${number(t.value)}</sys:Double>\n    <Thickness x:Key="${t.id}.thickness">${number(t.value)}</Thickness>\n    <CornerRadius x:Key="${t.id}.cornerRadius">${number(t.value)}</CornerRadius>\n`
        ).join('') + Object.entries(spec.themes).sort(([a], [b]) => compare(a, b)).map(([theme, values]) =>
            `    <ResourceDictionary x:Key="theme.${theme}">\n` + Object.entries(values).sort(([a], [b]) => compare(a, b)).map(([role, id]) =>
                `        <Color x:Key="theme.${role}.color">${wpfColor(tokens.find(t => t.id === id).value)}</Color>\n` +
                `        <SolidColorBrush x:Key="theme.${role}.brush" Color="{StaticResource ${id}}" />\n`
            ).join('') + '    </ResourceDictionary>\n'
        ).join('') + '</ResourceDictionary>\n';
}
