"""Generate native runtime pins from the registered Git submodules."""

import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[2]


def outputs(root):
    entry = subprocess.check_output(
        ['git', 'ls-files', '--stage', '--', '3rdparty/syncplay'], cwd=root, text=True).split()
    if len(entry) != 4 or entry[0] != '160000' or entry[2] != '0' or not re.fullmatch('[0-9a-f]{40}', entry[1]):
        raise ValueError('Syncplay runtime policy requires one registered source Gitlink')
    revision = entry[1]
    comment = '// Generated by tools/runtime-policy/generate.py; do not edit.\n'
    return {
        'packages/macos-bridge/Sources/SyncWatchBridge/HelperRuntimePolicy.swift':
            comment + f'enum HelperRuntimePolicy {{\n    static let syncplayRevision = "{revision}"\n}}\n',
        'packages/windows-bridge/SyncWatch.Bridge/HelperRuntimePolicy.cs':
            comment + 'namespace SyncWatch.Bridge;\n\n' +
            f'internal static class HelperRuntimePolicy {{ internal const string SyncplayRevision = "{revision}"; }}\n',
        'packages/linux-bridge/HelperRuntimePolicy.kt':
            comment + 'package syncwatch.bridge\n' +
            f'internal object HelperRuntimePolicy {{ const val syncplayRevision = "{revision}" }}\n',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in outputs(ROOT).items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                raise SystemExit('Stale native runtime policy: ' + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
    print('Native runtime policy matches source Gitlinks')


if __name__ == '__main__':
    main()
